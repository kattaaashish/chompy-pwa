// Regenerates src/audio-manifest.ts from whatever is in public/audio/. Runs
// before studio/still/render (npm pre-hooks), so dropping the ElevenLabs files
// in is enough — no code change needed to wire them up.
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const audio = join(here, "..", "public", "audio");
const FILES = ["music", "vo-1-snap", "vo-2-log", "vo-3-nutrition", "vo-4-ask", "vo-5-logo"];
const present = Object.fromEntries(FILES.map((f) => [f, existsSync(join(audio, `${f}.mp3`))]));

writeFileSync(
  join(here, "..", "src", "audio-manifest.ts"),
  `// Generated by tools/audio-manifest.mjs — do not edit. true == file exists in public/audio/.
export const AUDIO = ${JSON.stringify(present, null, 2)} as const;
`,
);
console.log("audio:", Object.entries(present).map(([k, v]) => `${k}=${v ? "yes" : "no"}`).join(" "));
